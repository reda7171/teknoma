function normalizeArabic(str: string) {
    return str.replace(/أ/g, 'ا')
              .replace(/إ/g, 'ا')
              .replace(/آ/g, 'ا')
              .replace(/ة/g, 'ه')
              .replace(/ي/g, 'ى')
              .replace(/[\u064B-\u065F]/g, '') // Remove tashkeel
              .trim()
              .toLowerCase();
}

async function main() {
    const lines = data.split('\n').map(l => l.trim()).filter(l => l);
    const updates = lines.map(line => {
        const parts = line.split('\t');
        if (parts.length >= 2) {
            return {
                title: parts[0].trim(),
                sku: parts[parts.length - 1].trim()
            };
        }
        return null;
    }).filter(x => x !== null) as {title: string, sku: string}[];

    const books = await prisma.book.findMany();
    let updatedCount = 0;
    
    for (const update of updates) {
        const normTarget = normalizeArabic(update.title);
        
        // Find matching books using EXACT match or very close match
        const matches = books.filter(b => normalizeArabic(b.title) === normTarget);
        
        if (matches.length > 0) {
            for (const match of matches) {
                try {
                    await prisma.book.update({
                        where: { id: match.id },
                        data: { sellerSku: update.sku }
                    });
                    updatedCount++;
                    console.log(`Updated "${match.title}" with SKU: ${update.sku}`);
                } catch (err: any) {
                    console.log(`Failed to update "${match.title}": ${err.message}`);
                }
            }
        } else {
            console.log(`Not found: "${update.title}"`);
        }
    }
    
    console.log(`Finished. Updated ${updatedCount} books.`);
}

main()
  .catch(e => {
    console.error(e);
    process.exit(1);
  })
